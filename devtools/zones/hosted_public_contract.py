#!/usr/bin/env python3
"""Generate original named-cell public entrances; no release or host-copy authority."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re
from capacity import REPO
from hosted_content import inventory
from hosted_capacity_layout import contracts

HEADER=REPO/'src/engine/server/library/serverUtility/src/shared/HostedPublicContract.h'


def contract(snapshot=None):
    snapshot=inventory() if snapshot is None else snapshot;layout=contracts(snapshot)
    source={(r['scene'],r['name']):r for r in snapshot['hosted_content']};controllers=[];entries=[]
    for item in layout['types']:
        if item['kind']!=3 or item['publisher']=='npe.npe_public_instance':continue
        if item['publisher'] not in ('systems.movement.public_instance_setup',
            'theme_park.dungeon.nova_orion_station.nova_orion_public_instance'):
            raise ValueError('Unreviewed public publisher API')
        original=source[(item['definition'],item['family'])];routes=original.get('entry_routes',[])
        if not routes or not item['rows'] or item['limit'] or item['static_footprint']:
            raise ValueError('Complete original public roots and explicit-limit contract required')
        seen=set()
        for route in routes:
            parts=route['destination'].split(':');cell=route.get('entry_cell')
            if (len(parts)!=7 or parts[:3]!=['instance',item['family'],item['definition']] or parts[3]!=cell or
                not isinstance(cell,str) or not re.fullmatch('[a-z][a-z0-9_]{0,48}',cell) or cell in ('none','world') or
                route['name'] in seen):raise ValueError('Original named-cell public entry required')
            point=dict(zip(('x','y','z'),map(float,parts[4:])))
            if any(not math.isfinite(v) or abs(v)>1000000 for v in point.values()):raise ValueError('Invalid original public local point')
            if any(float(route['position'][axis])!=point[axis] for axis in point) or route['position']['target']!=cell:
                raise ValueError('Inconsistent original public route point')
            seen.add(route['name']);entries.append(dict(definition=item['definition'],family=item['family'],route=route['name'],cell=cell,**point))
        controllers.append(dict(definition=item['definition'],family=item['family'],publisher=item['publisher'],roots=len(item['rows']),topology='portal'))
    controllers.sort(key=lambda r:(r['definition'],r['family']));entries.sort(key=lambda r:(r['definition'],r['family'],r['route']))
    inputs=dict(layout['input_sha256']);inputs['devtools/zones/hosted_public_contract.py']=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    value=dict(schema_version=1,layout_sha256=layout['contract_sha256'],controllers=controllers,entries=entries,input_sha256=inputs)
    value['contract_sha256']=hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    return value


def render(value):
    q=json.dumps
    out=['// Generated by devtools/zones/hosted_public_contract.py; do not edit.',
         '// Original portals and local entrances only; no runtime release authority.',
         '#ifndef INCLUDED_HostedPublicContract_H','#define INCLUDED_HostedPublicContract_H','#include <string>',
         'namespace HostedPublicContract','{',
         '    struct Controller {char const *definition,*family,*publisher;unsigned int roots;};',
         '    struct Entry {char const *definition,*family,*route,*cell;float x,y,z;};',
         '    inline char const *layoutDigest() {return '+q(value['layout_sha256'])+';}',
         '    inline char const *sourceDigest() {return '+q(value['contract_sha256'])+';}',
         '    inline Controller const *controllers(unsigned int &count)','    {','        static Controller const values[]={']
    for r in value['controllers']:out.append('            {%s,%s,%s,%d},'%(q(r['definition']),q(r['family']),q(r['publisher']),r['roots']))
    out+=['        };','        count=sizeof(values)/sizeof(values[0]);return values;','    }',
          '    inline Controller const *controller(std::string const &definition,std::string const &family)',
          '    {unsigned int count=0;Controller const *rows=controllers(count);',
          '     for(unsigned int n=0;n<count;++n)if(definition==rows[n].definition && family==rows[n].family)return rows+n;',
          '     return 0;}','    inline Entry const *entries(unsigned int &count)','    {','        static Entry const values[]={']
    for r in value['entries']:
        out.append('            {%s,%s,%s,%s,%sf,%sf,%sf},'%(q(r['definition']),q(r['family']),q(r['route']),q(r['cell']),repr(r['x']),repr(r['y']),repr(r['z'])))
    out+=['        };','        count=sizeof(values)/sizeof(values[0]);return values;','    }',
          '    inline std::string definition(std::string const &family)',
          '    {unsigned int count=0;Controller const *rows=controllers(count);std::string found;',
          '     for(unsigned int n=0;n<count;++n)if(family==rows[n].family)',
          '     {if(!found.empty())return std::string();found=rows[n].definition;}return found;}',
          '    inline Entry const *entrance(std::string const &definition,std::string const &family)',
          '    {unsigned int count=0;Entry const *rows=entries(count);Entry const *found=0;',
          '     for(unsigned int n=0;n<count;++n)if(definition==rows[n].definition && family==rows[n].family)',
          '     {if(found)return 0;found=rows+n;}return found;}',
          '}','#endif','']
    return '\n'.join(out)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write-header',action='store_true');parser.add_argument('--output',type=Path)
    args=parser.parse_args();value=contract();text=render(value)
    if args.write_header:HEADER.write_text(text)
    if not HEADER.exists() or HEADER.read_text()!=text:raise SystemExit('Original public entry contract is stale; regenerate explicitly')
    if args.output:
        with args.output.open('x') as stream:json.dump(value,stream,indent=2);stream.write('\n')
    print(json.dumps(dict(public_families=len(value['controllers']),original_entries=len(value['entries']),contract_sha256=value['contract_sha256'],runtime_activated=False)))


if __name__=='__main__':main()
