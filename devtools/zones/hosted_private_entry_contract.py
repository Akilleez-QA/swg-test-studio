#!/usr/bin/env python3
"""Original private entrance metadata; never access or runtime activation authority."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re
from capacity import REPO,SERVER_TABLES,read_table
from hosted_login_contract import model as login_model

HEADER=REPO/'src/engine/server/library/serverUtility/src/shared/HostedPrivateEntryContract.h'

def number(value,default,minimum=0,maximum=86400):
    result=int(value or default)
    if not minimum<=result<=maximum:raise ValueError('Original private entry integer is out of bounds')
    return result

def point(values):
    result=[float(v) for v in values]
    if len(result)!=3 or not all(math.isfinite(v) and abs(v)<=1000000 for v in result):
        raise ValueError('Bounded finite authored private point required')
    return result

def model():
    login=login_model();inputs={};tables={}
    for kind,path in ((1,SERVER_TABLES/'dungeon/space_dungeon.tab'),(2,SERVER_TABLES/'instance/instance_datatable.tab')):
        rows={}
        for _,row in read_table(REPO/path):
            if row['dungeon'] in rows:raise ValueError('Duplicate original dungeon row')
            rows[row['dungeon']]=row
        tables[kind]=rows;inputs[path.as_posix()]=hashlib.sha256((REPO/path).read_bytes()).hexdigest()
    random_path=Path('dsrc/sku.0/sys.server/compiled/game/script/library/space_dungeon_data.scriptlib')
    random_source=(REPO/random_path).read_text()
    if not all(re.search(r'loc\.'+axis+r'\s*\+=\s*\(-1\.0f\s*\+\s*\(2\.0f\s*\*\s*random\.rand\(\)\)\)\s*\*\s*startLocationRadius',random_source) for axis in ('x','z')):
        raise ValueError('Original axis-independent entrance randomization requires review')
    inputs[random_path.as_posix()]=hashlib.sha256((REPO/random_path).read_bytes()).hexdigest()
    entries=[]
    for family in login['families']:
        kind=family['kind']
        if kind>2:continue
        row=tables[kind][family['family']]
        common=dict(definition=family['definition'],family=family['family'],kind=kind,
            limit=number(row['max_players'],8 if kind==2 else 0,1,16384),
            min_players=number(row.get('min_players',''),0,0,32),duration=number(row['time_limit'],3600,1),
            required_key=row.get('key_required','') or ('none' if kind==2 else ''),
            variants=row.get('instanceType','') or ('dungeon_default' if kind==1 else ''),
            daily=kind==2 and row['lockoutTimer']=='daily',
            lockout_seconds=number(row['lockoutTimer'],0) if kind==1 else 0)
        if kind==2 and row['lockoutTimer'] not in ('','none','daily'):raise ValueError('Unknown original reset mode')
        if kind==1:
            radius=float(row['start_loc_radius'] or 0)
            if not math.isfinite(radius) or not 0<=radius<=100:raise ValueError('Unbounded original entrance radius')
            entries.append(dict(common,team=0,cell=row['start_cell_name'] or 'none',
                point=point(row[k] for k in ('start_loc_x','start_loc_y','start_loc_z')),radius=radius))
        else:
            for team in (1,2):
                raw=row['enter_one' if team==1 else 'enter_two']
                # A blank second team uses the old default origin. It is not
                # another authored entrance and cannot authorize private travel.
                if not raw:
                    if team==1:raise ValueError('Missing authored private entrance')
                    continue
                parts=raw.split(',')
                if len(parts)!=4:raise ValueError('Invalid original private cell/offset tuple')
                entries.append(dict(common,team=team,cell=parts[3],point=point(parts[:3]),radius=0.0))
    keys={(e['definition'],e['family'],e['team']) for e in entries}
    if len(keys)!=len(entries) or len({e['family'] for e in entries})!=15 or len({e['definition'] for e in entries})!=6:
        raise ValueError('Every dedicated hosted private/dungeon type requires exact entrances')
    for entry in entries:
        if not re.fullmatch('[a-z][a-z0-9_]{0,48}',entry['cell']):raise ValueError('Invalid authored cell name')
        if entry['min_players']>entry['limit']:raise ValueError('Original population minimum exceeds limit')
    data=dict(schema_version=1,login_contract_sha256=login['contract_sha256'],input_sha256=inputs,entries=entries,
        randomization='independent x/z offsets in [-radius,+radius]; y unchanged',runtime_activated=False)
    data['contract_sha256']=hashlib.sha256(json.dumps(data,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    return data

def render(data):
    q=lambda value:json.dumps(value)
    f=lambda value:repr(float(value))+'f'
    lines=['// Generated by devtools/zones/hosted_private_entry_contract.py.',
        '// Original geometry/access metadata only. No session or admission authority.',
        '#ifndef INCLUDED_HostedPrivateEntryContract_H','#define INCLUDED_HostedPrivateEntryContract_H',
        '#include "HostedLoginContract.h"','namespace HostedPrivateEntryContract','{',
        '    struct Entry {char const *definition,*family,*cell,*key,*variants;unsigned int kind,team,limit,minPlayers,duration,lockoutSeconds;bool daily;float x,y,z,radius;};',
        '    inline char const *sourceDigest(){return '+q(data['contract_sha256'])+';}',
        '    inline bool current(){return HostedLoginContract::current() && std::string(HostedLoginContract::sourceDigest())=='+q(data['login_contract_sha256'])+';}',
        '    inline Entry const *entries(unsigned int &count)','    {','        static Entry const rows[]={']
    for e in data['entries']:
        values=[q(e[k]) for k in ('definition','family','cell','required_key','variants')]
        values += [str(e[k]) for k in ('kind','team','limit','min_players','duration','lockout_seconds')]
        values += ['true' if e['daily'] else 'false']+[f(v) for v in e['point']]+[f(e['radius'])]
        lines.append('            {'+','.join(values)+'},')
    lines += ['        };','        count=sizeof(rows)/sizeof(rows[0]);return rows;','    }',
        '    inline Entry const *find(std::string const &scene,std::string const &family,unsigned int team)',
        '    {if(!current())return 0;unsigned int count=0;Entry const *rows=entries(count);',
        '     for(unsigned int n=0;n<count;++n)if(scene==rows[n].definition && family==rows[n].family && team==rows[n].team)return rows+n;',
        '     return 0;}',
        '    // Some private encounters include both a portal and outdoor space.',
        '    // Their original none-cell entrance makes the authored area the',
        '    // shared footprint; portal-only families retain container identity.',
        '    inline bool areaScoped(std::string const &scene,std::string const &family)',
        '    {',
        '        if(!current())return false;',
        '        unsigned int count=0;Entry const *rows=entries(count);bool outdoor=false;',
        '        for(unsigned int n=0;n<count;++n)if(scene==rows[n].definition && family==rows[n].family)',
        '        {if(rows[n].kind!=2)return false;if(std::string(rows[n].cell)=="none")outdoor=true;}',
        '        return outdoor;',
        '    }',
        '    // The original randomized start uses a square, independently on x/z.',
        '    // Inputs are root-relative outdoors and cell-local for interiors.',
        '    inline bool contains(Entry const &entry,std::string const &cell,float x,float y,float z)',
        '    {',
        '        if(find(entry.definition,entry.family,entry.team)!=&entry || cell!=entry.cell ||',
        '            !HostedLoginContract::finite(x) || !HostedLoginContract::finite(y) || !HostedLoginContract::finite(z))return false;',
        '        float const tolerance=0.001f;',
        '        return x>=entry.x-entry.radius-tolerance && x<=entry.x+entry.radius+tolerance &&',
        '            z>=entry.z-entry.radius-tolerance && z<=entry.z+entry.radius+tolerance &&',
        '            y>=entry.y-tolerance && y<=entry.y+tolerance;',
        '    }','}','#endif','']
    return '\n'.join(lines)

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write-header',action='store_true');parser.add_argument('--output',type=Path);args=parser.parse_args()
    data=model();expected=render(data)
    if args.write_header:HEADER.write_text(expected)
    if not HEADER.exists() or HEADER.read_text()!=expected:raise SystemExit('Private entry contract is stale; regenerate explicitly')
    if args.output:
        with args.output.open('x') as stream:json.dump(data,stream,indent=2);stream.write('\n')
    print(json.dumps(dict(families=15,hosts=6,entries=len(data['entries']),contract_sha256=data['contract_sha256'],runtime_activated=False)))

if __name__=='__main__':main()
