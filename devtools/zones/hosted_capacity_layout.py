#!/usr/bin/env python3
"""Generate exact authored controller footprints; source proof is not release approval."""
import argparse
import hashlib
import json
from pathlib import Path
import re

from capacity import REPO
from hosted_content import inventory
from instance_scope import load as load_scope

HEADER=REPO/'src/engine/server/library/serverUtility/src/shared/HostedContentContract.h'
KINDS={'dungeon':1,'private_instance':2,'public_instance':3}
PUBLISHERS={1:('theme_park.dungeon.space_dungeon_controller',),
            2:('systems.instance.instance_manager',),
            3:('npe.npe_public_instance','systems.movement.public_instance_setup',
               'theme_park.dungeon.nova_orion_station.nova_orion_public_instance')}


def contracts(report=None):
    report=inventory() if report is None else report
    if report.get('template_controller_gaps'):
        raise ValueError('Incomplete controller-template inheritance cannot produce a native footprint')
    scope=load_scope();known={r['definition'] for r in scope['definitions']}
    inputs=dict(report['input_sha256']);types=[];slots=[];seen=set();positions=set();occupied_rows=set()
    for f in report['hosted_content']:
        scene,name,source_kind=f['scene'],f['name'],f['kind']
        if scene not in known or source_kind not in KINDS or not re.fullmatch('[a-z][a-z0-9_]{0,127}',name):
            raise ValueError('Unknown or noncanonical hosted identity')
        kind=KINDS[source_kind]
        if source_kind=='public_instance' and name=='rryatt_trail':kind=4
        if (scene,name) in seen:raise ValueError('Duplicate authored family')
        seen.add((scene,name))
        rows=[]
        for placement in f['placements']:
            if placement['scene']!=scene:raise ValueError('Cross-scene root placement')
            for row in placement['rows']:
                if type(row) is not int or not 0<=row<1000000 or row in rows:
                    raise ValueError('Invalid or duplicate authored root row')
                rows.append(row)
        script=''
        if rows:
            controllers=f['controllers']
            if len(controllers)!=1 or not controllers[0].get('template_declarations_complete'):
                raise ValueError('One complete authored controller declaration required')
            candidates=set(controllers[0].get('scripts',()))&set(PUBLISHERS[KINDS[source_kind]])
            if len(candidates)!=1:raise ValueError('Ambiguous or missing authored publisher script')
            script=next(iter(candidates))
            if set(controllers[0]['placement_rows'])!=set(rows):
                raise ValueError('Controller declaration does not cover the exact authored rows')
        elif source_kind!='dungeon':raise ValueError('Unresolved non-dungeon placement')
        maximum=f.get('max_players')
        if maximum is None:maximum=0
        if type(maximum) is not int or not 0<=maximum<=16384 or (kind<=2 and maximum==0):
            raise ValueError('Invalid authored family limit')
        if maximum and len(rows)*maximum>1000000:raise ValueError('Authored family exceeds native capacity bound')
        static=bool(rows and kind<=2)
        exits=([f['exit_scene']] if source_kind=='dungeon' else
               sorted({e['target'] for e in f['exits']}) if source_kind=='private_instance' else [])
        if any(e not in known for e in exits):raise ValueError('Unknown authored exit definition')
        types.append(dict(definition=scene,family=name,kind=kind,limit=maximum,rows=sorted(rows),
                          publisher=script,static_footprint=static,exit_definitions=exits))
        for row in sorted(rows):
            key=scene,name,row
            if key in positions or (scene,row) in occupied_rows:raise ValueError('Duplicate or overlapping footprint slot')
            positions.add(key);occupied_rows.add((scene,row));slots.append(dict(definition=scene,family=name,kind=kind,row=row,limit=maximum))
    for relative in ('devtools/zones/family_scope.json','devtools/zones/instance_definitions.py',
                     'devtools/zones/hosted_content.py','devtools/zones/template_controller_evidence.py',
                     'devtools/zones/hosted_capacity_layout.py'):
        inputs[relative]=hashlib.sha256((REPO/relative).read_bytes()).hexdigest()
    types.sort(key=lambda f:(f['definition'],f['family']));slots.sort(key=lambda f:(f['definition'],f['family'],f['row']))
    digest=hashlib.sha256(json.dumps(dict(inputs=inputs,types=types,slots=slots),sort_keys=True,separators=(',',':')).encode()).hexdigest()
    return dict(schema_version=1,types=types,slots=slots,input_sha256=inputs,contract_sha256=digest)


def render(report=None):
    report=contracts() if report is None else report
    q=json.dumps
    out=['// Generated by devtools/zones/hosted_capacity_layout.py; do not hand edit.',
         '// Exact authored roots only. This does not authorize release, copies or retirement.',
         '#ifndef INCLUDED_HostedContentContract_H','#define INCLUDED_HostedContentContract_H',
         '#include <map>','#include <string>','namespace HostedContentContract','{',
         '    struct Type {char const *definition,*family;int kind,limit;unsigned int count;char const *publisher;bool boundedRows;};',
         '    struct Slot {char const *definition,*family;int kind,row,limit;};',
         '    inline char const *sourceDigest() {return '+q(report['contract_sha256'])+';}',
         '    inline Type const *types(unsigned int &count)','    {','        static Type const rows[]={']
    for f in report['types']:
        out.append('            {%s,%s,%d,%d,%d,%s,%s},'%(q(f['definition']),q(f['family']),f['kind'],f['limit'],len(f['rows']),q(f['publisher']),'true' if f['static_footprint'] else 'false'))
    out+=['        };','        count=sizeof(rows)/sizeof(rows[0]);return rows;','    }',
          '    inline Slot const *slots(unsigned int &count)','    {','        static Slot const rows[]={']
    for f in report['slots']:
        out.append('            {%s,%s,%d,%d,%d},'%(q(f['definition']),q(f['family']),f['kind'],f['row'],f['limit']))
    out+=['        };','        count=sizeof(rows)/sizeof(rows[0]);return rows;','    }',
          '    inline Type const *type(std::string const &definition,std::string const &family)',
          '    {unsigned int count=0;Type const *rows=types(count);',
          '     for(unsigned int n=0;n<count;++n) {if(definition==rows[n].definition && family==rows[n].family)return rows+n;}',
          '     return 0;}',
          '    inline Slot const *slot(std::string const &definition,std::string const &family,int row)',
          '    {unsigned int count=0;Slot const *rows=slots(count);',
          '     for(unsigned int n=0;n<count;++n) {if(row==rows[n].row && definition==rows[n].definition && family==rows[n].family)return rows+n;}',
          '     return 0;}',
          '    inline bool minima(std::string const &definition,std::map<std::string,unsigned int> &out)',
          '    {','        out.clear();unsigned int count=0;Type const *rows=types(count);',
          '        for(unsigned int n=0;n<count;++n)if(definition==rows[n].definition)',
          '        {if(!rows[n].boundedRows || !rows[n].count || rows[n].limit<1) {out.clear();return false;}',
          '         out[rows[n].family]=rows[n].count*static_cast<unsigned int>(rows[n].limit);}',
          '        return !out.empty();','    }','}','#endif','']
    return '\n'.join(out)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-header',action='store_true')
    parser.add_argument('--output',type=Path,help='fresh source-contract evidence path')
    args=parser.parse_args();report=contracts();expected=render(report)
    if args.write_header:HEADER.write_text(expected)
    if not HEADER.exists() or HEADER.read_text()!=expected:raise SystemExit('Authored native footprint is stale; regenerate explicitly')
    if args.output:
        with args.output.open('x') as f:json.dump(report,f,sort_keys=True,indent=2);f.write('\n')
    print(json.dumps(dict(types=len(report['types']),slots=len(report['slots']),contract_sha256=report['contract_sha256'])))

if __name__=='__main__':main()
