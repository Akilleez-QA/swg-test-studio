"""Explicit world ownership scope, separate from per-family release eligibility."""
import argparse
from pathlib import Path
import shlex

from capacity import REPO, read_json
from instance_definitions import definitions

SCOPE=Path(__file__).with_name('family_scope.json')
HEADER=REPO/'src/engine/server/library/serverUtility/src/shared/ZoneInstanceScope.h'
MODES={'persistent_single':'PersistentSingle','owned_room_host':'OwnedRoomHost',
       'session_host':'SessionHost','dynamic_area':'DynamicArea','piloted_space':'PilotedSpace'}


def load(path=SCOPE):
    value=read_json(path)
    if (not isinstance(value,dict) or set(value)!={'schema_version','revision','definitions'} or
            type(value['schema_version']) is not int or value['schema_version']!=1 or
            not isinstance(value['revision'],str) or not value['revision'] or
            not isinstance(value['definitions'],list)):
        raise ValueError('Invalid instance scope catalog')
    expected={d['name'] for d in definitions()['definitions']}
    seen=set()
    for row in value['definitions']:
        if (not isinstance(row,dict) or set(row)!={'definition','mode'} or
                not isinstance(row['definition'],str) or row['definition'] not in expected or
                row['definition'] in seen or not isinstance(row['mode'],str) or row['mode'] not in MODES):
            raise ValueError('Unknown, duplicate or invalid canonical scope')
        seen.add(row['definition'])
    if seen!=expected:
        raise ValueError('Every canonical definition needs an explicit world scope')
    return value


def allows_instances(name, catalog=None):
    catalog=load() if catalog is None else catalog
    return any(r['definition']==name and r['mode'] not in ('persistent_single','owned_room_host')
               for r in catalog['definitions'])


def validate_instance_policies(text):
    """Reject a prohibited native policy before rewriting any generated config."""
    catalog=load();section='';seen=set()
    for raw in text.splitlines():
        line=raw.strip()
        if line.startswith('['):section=line
        key,sep,value=line.partition('=')
        if section!='[CentralServer]' or key.strip()!='zoneInstancePolicy' or not sep:
            continue
        # ConfigFile stores one quoted policy value. Parse its words without
        # shell expansion or execution, preserving the native seven-field form.
        fields=shlex.split(value,comments=True)
        if len(fields)==1:fields=fields[0].split()
        if len(fields)!=7 or fields[0] in seen or not allows_instances(fields[0],catalog):
            raise ValueError('Instance policy requires an eligible canonical non-persistent definition')
        seen.add(fields[0])
    return seen


def render(catalog=None):
    catalog=load() if catalog is None else catalog
    rows=sorted(catalog['definitions'],key=lambda r:r['definition'])
    aliases=sorted((alias,d['name']) for d in definitions()['definitions'] for alias in d['legacy_aliases'])
    output=['// Generated by devtools/zones/instance_scope.py from family_scope.json.',
            '// Scope permits integration; it does not grant runtime release eligibility.',
            '#ifndef INCLUDED_ZoneInstanceScope_H','#define INCLUDED_ZoneInstanceScope_H',
            '#include <string>','namespace ZoneInstanceScope','{',
            '    enum Mode { Unknown, PersistentSingle, OwnedRoomHost, SessionHost, DynamicArea, PilotedSpace };',
            '    inline Mode mode(std::string const &definition)','    {',
            '        struct Entry { char const *name; Mode mode; };',
            '        static Entry const entries[]={']
    output += ['            {"%s",%s},'%(r['definition'],MODES[r['mode']]) for r in rows]
    output += ['        };','        for(unsigned int n=0;n<sizeof(entries)/sizeof(entries[0]);++n)',
               '            if(definition==entries[n].name)return entries[n].mode;','        return Unknown;','    }',
               '    inline bool legacyAlias(std::string const &definition)','    {']
    output += ['        if(definition=="%s")return true;'%a for a,_ in aliases]
    output += ['        return false;','    }',
               '    inline std::string definitionAt(unsigned int index)','    {',
               '        static char const *const definitions[]={'+','.join('"'+r['definition']+'"' for r in rows)+'};',
               '        return index<sizeof(definitions)/sizeof(definitions[0])?definitions[index]:std::string();','    }',
               '    inline std::string canonical(std::string const &scene)','    {',
               '        if(mode(scene)!=Unknown)return scene;']
    output += ['        if(scene=="%s")return "%s";'%(a,d) for a,d in aliases]
    output += ['        return std::string();','    }',
               '    inline std::string playerFamily(std::string const &scene)','    {',
               '        std::string const definition=canonical(scene);',
               '        Mode const value=mode(definition);',
               '        return (value==PilotedSpace || (value==DynamicArea && definition!="kashyyyk_rryatt_trail"))?',
               '            "world:"+definition:std::string();','    }',
               '    inline std::string familyDefinition(std::string const &family)','    {',
               '        if(family.size()<=6 || family.substr(0,6)!="world:")return std::string();',
               '        std::string const definition=family.substr(6);',
               '        return canonical(definition)==definition && playerFamily(definition)==family?',
               '            definition:std::string();','    }',
               '    inline bool allowsInstances(std::string const &definition)','    {',
               '        Mode const value=mode(definition);',
               '        return value==SessionHost || value==DynamicArea || value==PilotedSpace;','    }',
               '}','#endif','']
    return '\n'.join(output)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-header',action='store_true',help='regenerate the checked-in native scope header')
    args=parser.parse_args()
    expected=render()
    if args.write_header:HEADER.write_text(expected)
    if HEADER.read_text()!=expected:raise SystemExit('Native instance scope is stale; regenerate it')
    print('Instance scope covers all 39 canonical definitions; persistent planets stay single.')


if __name__=='__main__':main()
